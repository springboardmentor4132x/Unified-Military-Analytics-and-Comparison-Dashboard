def clean_numeric(val):
    if pd.isna(val):
        return None

    val = str(val)

    # 1. Remove line breaks, tabs, extra spaces
    val = re.sub(r"\s+", " ", val)

    # 2. Convert to lowercase
    val = val.lower()

    # 3. Remove commas and common symbols
    val = re.sub(r"[,$%+]", "", val)

    # 4. Remove unit labels (handles Cu.M, mt, etc.)
    val = re.sub(r"(cu\.m|cum|mt|bbl|km|usd)", "", val)

    return val.strip()

