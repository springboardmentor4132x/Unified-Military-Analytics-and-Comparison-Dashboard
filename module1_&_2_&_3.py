#Total air power = Sum of all Aircraft Types
df["total_aircraft"] = (
    df["fighter_aircraft"] +
    df["attack_aircraft"] +
    df["transport_aircraft"] +
    df["trainer_aircraft"] +
    df["special_mission_aircraft"] +
    df["tanker_aircraft"] +
    df["helicopters"] +
    df["attack_helicopters"]
)

df[["country", "total_aircraft"]].head()

#Total Ground Power = Tanks + Armored Vehicles+ Artillery
df["total_ground_power"] = (
    df["tanks"] +
    df["armored_vehicles"] +
    df["self_propelled_artillery"] +
    df["towed_artillery"] +
    df["rocket_projectors"]
)

df[["country", "total_ground_power"]].head()

#Combined Military Strength indicator.
df["overall_military_assets"] = (
    df["total_aircraft"] + df["total_ground_power"]
)

df[["country", "overall_military_assets"]].head()

#Air to Ground Ratio - Shows air power dominance VS Ground power
df["air_to_ground_ratio"] = (
    df["total_aircraft"] / (df["total_ground_power"] + 1)
)

#Rank country based on overall asset
df["military_rank"] = (
    df["overall_military_assets"]
    .rank(ascending=False, method="dense")
)

