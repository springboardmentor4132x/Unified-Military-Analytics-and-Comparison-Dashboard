#creating reusable function
import re
import requests
from bs4 import BeautifulSoup

headers = {"User-Agent": "Mozilla/5.0"}

def scrape_country_metrics(url):
    response = requests.get(url, headers=headers, timeout=15)
    soup = BeautifulSoup(response.text, "lxml")

    scripts = soup.find_all("script")
    metrics = {}

    for script in scripts:
        if script.string and "var" in script.string:
            matches = re.findall(r"var\s+([a-zA-Z0-9_]+)\s*=\s*([0-9]+)", script.string)
            for key, value in matches:
                metrics[key] = int(value)

    country_name = soup.title.text.replace("2025", "").replace("Military Strength", "").strip()
    metrics["Country"] = country_name

    return metrics

