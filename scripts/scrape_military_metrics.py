url_status = {}  # to store success/failure for each URL

for url, metric in URLS.items():
    try:
        response = requests.get(url, headers=HEADERS, timeout=20)
        response.raise_for_status()

        soup = BeautifulSoup(response.text, "html.parser")
        records = soup.find_all("div", class_="recordsetContainer")

        if not records:
            url_status[url] = "No records found"
            continue

        for record in records:
            country_tag = record.find("div", class_="longFormName")
            value_tag = record.find("div", class_="pwrIndxContainer") if metric == "pwr_index" else record.find("div", class_="valueContainer")

            if country_tag and value_tag:
                country = country_tag.text.strip()
                value_span = value_tag.find("span")
                value = value_span.text.strip() if value_span else value_tag.text.strip()

                if country not in all_data:
                    all_data[country] = {}
                all_data[country][metric] = value

        url_status[url] = "Success"
        time.sleep(1)

    except Exception as e:
        url_status[url] = f"Failed: {str(e)}"
