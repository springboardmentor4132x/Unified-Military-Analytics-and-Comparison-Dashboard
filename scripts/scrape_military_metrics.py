HEADERS = {
    "User-Agent": "Mozilla/5.0"
}
all_data = {}

for url, metric in URLS.items():
    try:
        response = requests.get(url, headers=HEADERS, timeout=20)
        response.raise_for_status()

        soup = BeautifulSoup(response.text, "html.parser")
        records = soup.find_all("div", class_="recordsetContainer")

        for record in records:
            country_tag = record.find("div", class_="longFormName")

            # Correct pwr_index parsing for base URL
            if metric == 'pwr_index':
                value_tag = record.find("div", class_="pwrIndxContainer")
            else:
                value_tag = record.find("div", class_="valueContainer")

            if not country_tag or not value_tag:
                continue

            country = country_tag.text.strip()
            # get <span> if exists, else text
            value_span = value_tag.find("span")
            value = value_span.text.strip() if value_span else value_tag.text.strip()

            if country not in all_data:
                all_data[country] = {}

            all_data[country][metric] = value

        time.sleep(1)

    except Exception:
        pass

df = pd.DataFrame.from_dict(all_data, orient="index")
df.reset_index(inplace=True)
